#!/bin/bash
# =============================================================================
# EzExam Secure Local Database Setup Script
# =============================================================================
# This script runs locally on your machine.
# Passwords are read interactively with 'read -s' (hidden, not echoed or logged).
# Creates dedicated 'ezexam_app' user restricted ONLY to the 'ezexam' database.
# =============================================================================

set -e

# Resolve MySQL binary
if [ -x "/usr/local/mysql/bin/mysql" ]; then
    MYSQL="/usr/local/mysql/bin/mysql"
elif command -v mysql >/dev/null 2>&1; then
    MYSQL=$(command -v mysql)
else
    echo "ERROR: MySQL client binary not found."
    exit 1
fi

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SCHEMA_FILE="$SCRIPT_DIR/backend/src/main/resources/schema.sql"
SEED_FILE="$SCRIPT_DIR/backend/src/main/resources/seed.sql"
PROPS_FILE="$SCRIPT_DIR/backend/src/main/resources/db.properties"

echo "=========================================================="
echo "  EzExam — Secure Local MySQL Setup"
echo "=========================================================="
echo "MySQL client: $MYSQL"
echo ""

# 1. Prompt for MySQL admin credentials
read -p "Enter MySQL administrative username [root]: " ADMIN_USER
ADMIN_USER=${ADMIN_USER:-root}

echo -n "Enter password for '$ADMIN_USER' (input is hidden): "
read -s ADMIN_PASS
echo ""

# Verify connection
if ! "$MYSQL" -u "$ADMIN_USER" -p"$ADMIN_PASS" -e "SELECT 1;" >/dev/null 2>&1; then
    echo "ERROR: Could not connect to MySQL with user '$ADMIN_USER'. Check credentials."
    exit 1
fi

echo " Connection to MySQL verified."

# 2. Check existing databases
EXISTS=$("$MYSQL" -u "$ADMIN_USER" -p"$ADMIN_PASS" -N -s -e \
    "SELECT COUNT(*) FROM information_schema.schemata WHERE schema_name = 'ezexam';")

if [ "$EXISTS" -gt 0 ]; then
    echo "ℹ️  Database 'ezexam' already exists."
    TABLE_COUNT=$("$MYSQL" -u "$ADMIN_USER" -p"$ADMIN_PASS" -N -s -e \
        "SELECT COUNT(*) FROM information_schema.tables WHERE table_schema = 'ezexam';")
    echo "ℹ️  Existing table count in 'ezexam': $TABLE_COUNT"
else
    echo "Creating database 'ezexam'..."
    "$MYSQL" -u "$ADMIN_USER" -p"$ADMIN_PASS" -e \
        "CREATE DATABASE IF NOT EXISTS \`ezexam\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;"
    echo " Database 'ezexam' created."
fi

# 3. Create or update dedicated application user 'ezexam_app'
echo ""
echo "Creating dedicated application user 'ezexam_app'..."
read -p "Enter password for new 'ezexam_app' user [press ENTER to generate random]: " APP_PASS
if [ -z "$APP_PASS" ]; then
    APP_PASS=$(openssl rand -base64 12 | tr -dc 'a-zA-Z0-9' | head -c 16)
    echo "Generated secure password for 'ezexam_app'."
fi

"$MYSQL" -u "$ADMIN_USER" -p"$ADMIN_PASS" <<EOF
CREATE USER IF NOT EXISTS 'ezexam_app'@'localhost' IDENTIFIED BY '$APP_PASS';
ALTER USER 'ezexam_app'@'localhost' IDENTIFIED BY '$APP_PASS';
GRANT ALL PRIVILEGES ON \`ezexam\`.* TO 'ezexam_app'@'localhost';
FLUSH PRIVILEGES;
EOF
echo " User 'ezexam_app' created with privileges restricted to 'ezexam.*'."

# 4. Import schema and seed data
echo ""
echo "Importing schema..."
"$MYSQL" -u "ezexam_app" -p"$APP_PASS" ezexam < "$SCHEMA_FILE"
echo " Schema imported successfully."

echo "Importing seed data (non-destructive INSERT IGNORE)..."
"$MYSQL" -u "ezexam_app" -p"$APP_PASS" ezexam < "$SEED_FILE"
echo " Seed data imported successfully."

# 5. Write db.properties (gitignored)
cat > "$PROPS_FILE" <<EOF
# EzExam Database Configuration (Auto-generated by setup-db.sh)
db.url=jdbc:mysql://localhost:3306/ezexam?useSSL=false&allowPublicKeyRetrieval=true&serverTimezone=UTC
db.user=ezexam_app
db.password=$APP_PASS
EOF
chmod 600 "$PROPS_FILE"
echo " Wrote credentials to gitignored $PROPS_FILE (chmod 600)."

# 6. Rebuild WAR and deploy to Tomcat
echo ""
echo "Rebuilding backend with updated db.properties..."
cd "$SCRIPT_DIR/backend"
mvn clean package -DskipTests=true >/dev/null

WAR_SRC="$SCRIPT_DIR/backend/target/ezexam.war"
TOMCAT_WEBAPPS="/opt/homebrew/Cellar/tomcat@10/10.1.61/libexec/webapps"
if [ -d "$TOMCAT_WEBAPPS" ]; then
    echo "Redeploying to Tomcat ($TOMCAT_WEBAPPS)..."
    cp "$WAR_SRC" "$TOMCAT_WEBAPPS/ezexam.war"
    
    # Restart Tomcat cleanly
    /opt/homebrew/opt/tomcat@10/bin/catalina stop 5 -force >/dev/null 2>&1 || true
    sleep 2
    /opt/homebrew/opt/tomcat@10/bin/catalina start >/dev/null
    echo " Tomcat restarted and application deployed."
fi

echo ""
echo "=========================================================="
echo "  Setup Completed Successfully!"
echo "=========================================================="
echo "  MySQL User     : ezexam_app"
echo "  Database       : ezexam"
echo "  Config File    : backend/src/main/resources/db.properties"
echo "  API Endpoint   : http://localhost:8080/ezexam/api/auth/me"
echo "=========================================================="
